// Защита от устаревших ответов («последний выиграл»).
//
// Зачем. Экраны админки грузят данные по смене вкладки, воркспейса и фильтра, и до
// 07.08.2026 ни один не проверял, его ли это ответ. Два наблюдаемых следствия, оба
// на реальных таймингах (замер /api/sources — 3.8 с):
//
//   • Ответ ПРЕДЫДУЩЕГО запроса приходит позже. Его `catch` пишет ошибку в общий
//     `this.error`, и StateBlock рисует «Ошибка загрузки» ВМЕСТО уже загруженных
//     строк текущей вкладки — ветка error в StateBlock стоит перед слотом. Снять
//     её можно только кнопкой «Повторить», потому что вкладка помечена загруженной.
//   • Ответ предыдущего приходит РАНЬШЕ. Его `finally` гасит `loading`, пока запрос
//     текущей вкладки ещё в полёте, и экран печатает «Данных нет» — утверждение
//     факта, которого нет.
//
// Худший случай — GraphView: устаревший ответ уничтожает инстанс cytoscape и
// перестраивает граф, так что на экране оказывается граф ПРОШЛОГО воркспейса при
// новом значении в фильтре, и по виду это неотличимо от правды.
//
// Почему счётчик, а не AbortController. Отмена запроса убирает симптом только для
// сети; гонка возможна и между двумя успешными ответами. Счётчик закрывает класс
// целиком и не требует прокидывать signal через весь слой api.js. Отмену имеет
// смысл добавить сверху отдельно — ради экономии трафика, а не корректности.
//
// Использование в Options API:
//
//   import { newSequence } from '../reqseq.js';
//   data() { return { seq: newSequence() }; },
//   async load() {
//     const fresh = this.seq.next();
//     this.loading = true;
//     try {
//       const data = await api.get(...);
//       if (!fresh()) return;          // пришёл ответ на отменённый вопрос
//       this.rows = data.items;
//     } catch (e) {
//       if (!fresh()) return;
//       this.error = e;
//     } finally {
//       if (fresh()) this.loading = false;
//     }
//   }
//
// `fresh()` проверяется перед КАЖДОЙ записью в состояние, включая `finally`:
// именно пропуск проверки в `finally` и давал ложное «данных нет».

export function newSequence() {
  let current = 0;
  return {
    /** Объявить новый запрос и получить проверку «мой ли ответ». */
    next() {
      const mine = ++current;
      return () => mine === current;
    },
    /** Отменить всё, что в полёте, ничего не начиная (например, при unmount). */
    cancel() {
      current += 1;
    },
  };
}
