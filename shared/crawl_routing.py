"""Выбор маршрута для краула: напрямую или через прокси.

Живёт в `shared/`, а не в `crawl4ai/`, по прозаической причине: каталог
`crawl4ai/` не является пакетом (у него свой Dockerfile и собственный WORKDIR),
поэтому его модули не импортируются из тестов. Логика маршрутизации при этом
ровно та, которую надо проверять построчно, а не по AST.

Почему маршрут вообще выбирается. У сервиса два пути наружу, и прокси есть
только у одного:

  * обычная `aiohttp`-сессия ходит НАПРЯМУЮ;
  * браузерный путь (Playwright) поднимается с `socks5://xray:10808`.

К части хостов прямой выход мёртв на TLS-рукопожатии. Замер 2026-08-05 из
контейнера crawl4ai: `substack.com`, `uxdesign.cc`, `thegradient.pub`,
`medium.com` — `ConnectTimeout` напрямую и `200` через прокси. Значит выбор
маршрута — это вопрос ДОСТИЖИМОСТИ, а не типа контента, как считалось раньше.
"""

from __future__ import annotations

from urllib.parse import urlparse

# Публикации Medium живут на поддоменах сплошь (`leohuax.medium.com`), а
# сравнение было точным — по списку `{"medium.com", "www.medium.com"}`.
# Поддомены в браузерный путь не попадали, уходили в сессию без прокси и
# отваливались по таймауту. Суффиксное совпадение здесь исправляет недосмотр,
# а не расширяет область.
BROWSER_HOST_SUFFIXES: tuple[str, ...] = ("medium.com",)

# Хосты, к которым прямой путь не работает. Множество наполняется на лету:
# первый же таймаут помечает хост, и следующие краулы к нему идут через прокси.
DEAD_ROUTE_SET = "crawl4ai:dead_direct_routes"

# TTL пометки. Без него разовый сбой сети превратился бы в постоянный обход
# через браузер, который дороже прямого запроса в разы. Неделя — компромисс:
# достаточно долго, чтобы не переоткрывать одно и то же каждый день, и
# достаточно коротко, чтобы починка маршрута сама себя учла.
DEAD_ROUTE_TTL = 7 * 24 * 3600


def host_of(url: str) -> str:
    """Хост URL без порта, в нижнем регистре."""
    return (urlparse(url or "").hostname or "").lower()


def is_browser_host(url: str) -> bool:
    """Хост, который всегда обслуживается браузерным путём.

    Совпадение суффиксное и с точкой: `evilmedium.com.attacker.net` не должен
    считаться Medium, иначе достаточно зарегистрировать похожее имя, чтобы
    отправить наш браузер куда угодно.
    """
    host = host_of(url)
    if not host:
        return False
    return any(
        host == suffix or host.endswith("." + suffix) for suffix in BROWSER_HOST_SUFFIXES
    )
